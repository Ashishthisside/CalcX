#calculator for beginners
num1 =float(input("enter num:"))
num2 =float(input("enter num:"))
op = input("enter operator (+,-,*,/,%,**):")
if op== '+':
    print(num1+num2)
elif op== '-':
    print(num1-num2)
elif op== '*':
    print(num1*num2)
elif op== '/':
    print(num1/num2)
elif op== '%':
    print(num1%num2)
elif op== '**':
    print(num1**num2)
else:
    print("invalid operator")
    

            
                  